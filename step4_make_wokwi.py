"""Step 4 (no hardware yet): play one cup game with real brain signals, then turn it into an
Arduino program you can run in the free online simulator Wokwi (https://wokwi.com).

  * The "brain" part runs here in Python: real EEG trials of one person, read by the
    detector trained on the OTHER 5 people, with the "90% sure + final check" rule.
  * The game is saved into wokwi/sketch.ino. On the Arduino:
        base servo (pin 9)    turns the arm to each cup
        gripper servo (pin 10) closes when the arm grabs
        red LED (pin 12)      = brain says "oops"
        green LED (pin 11)    = brain says "ok"
    and the Serial Monitor tells the story move by move.
  * wokwi/diagram.json is the wiring, ready to paste into Wokwi.

The same sketch runs on a real Arduino later (same pins).

    python step4_make_wokwi.py --person 6
    python step4_make_wokwi.py --person 6 --seed 3     # another game
    python step4_make_wokwi.py --synthetic             # quick test, no download
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from step3_sim_arm import MAX_MOVES, N_CUPS, train_on_others

SURE = 0.90


def play_recorded(oops_pool, ok_pool, hit, false, rng):
    """'90% sure + final check' game that remembers every step: (kind, cup, oops).
    kind 0 = move to a cup, kind 1 = reach for a cup and check the brain once more."""
    target = int(rng.integers(N_CUPS))
    pos = N_CUPS // 2
    belief = np.full(N_CUPS, 1 / N_CUPS)
    cups = np.arange(N_CUPS)
    steps = []

    def brain_says_oops(is_error):
        pool = oops_pool if is_error else ok_pool
        return bool(pool[rng.integers(len(pool))])

    while len(steps) < MAX_MOVES:
        if belief.max() >= SURE:
            choice = int(np.argmax(belief))
            oops = brain_says_oops(choice != target)
            steps.append((1, choice, oops))
            if not oops:
                return target, choice, steps
            like = np.where(cups == choice, false, hit)
            belief = belief * like / (belief * like).sum()
            continue
        guess = int(np.argmax(belief))
        if guess != pos:
            step = 1 if guess > pos else -1
        else:
            step = int(rng.choice([-1, 1])) if 0 < pos < N_CUPS - 1 else (1 if pos == 0 else -1)
        new = pos + step
        away = np.abs(new - cups) > np.abs(pos - cups)
        oops = brain_says_oops(bool(away[target]))
        like = np.where(away, hit if oops else 1 - hit, false if oops else 1 - false)
        belief = belief * like / (belief * like).sum()
        steps.append((0, new, oops))
        pos = new
    return target, int(np.argmax(belief)), steps


SKETCH = """// ErrP robot arm: one cup game guided by real brain "oops" signals
// Generated by step4_make_wokwi.py ({label}).
// Base servo: pin 9. Gripper servo: pin 10. Green LED (ok): pin 11. Red LED (oops): pin 12.
#include <Servo.h>

const int N_STEPS = {n};
const byte KIND[N_STEPS] = {{{kind}}};  // 0 = move to a cup, 1 = reach + final brain check
const byte CUP[N_STEPS]  = {{{cup}}};   // cup 0..4 (shown as 1..5)
const byte OOPS[N_STEPS] = {{{oops}}};  // what the detector said: 1 = oops, 0 = ok
const byte WANTED = {target};          // the cup the person wanted (the arm does not know this)
const byte START_CUP = {start};
const byte CHOICE = {choice};         // the cup the arm finally grabs

const int GREEN = 11, RED = 12;
Servo base, grip;
int angle;

int angleFor(byte cup) {{ return 160 - 35 * cup; }}  // cup 1 on the left ... cup 5 on the right

void turnTo(int target) {{
  while (angle != target) {{
    angle += (target > angle) ? 1 : -1;
    base.write(angle);
    delay(12);
  }}
}}

void showBrain(byte oops) {{
  digitalWrite(oops ? RED : GREEN, HIGH);
  Serial.println(oops ? "   brain: OOPS!" : "   brain: ok");
  delay(900);
  digitalWrite(RED, LOW);
  digitalWrite(GREEN, LOW);
}}

void setup() {{
  Serial.begin(9600);
  pinMode(GREEN, OUTPUT);
  pinMode(RED, OUTPUT);
  base.attach(9);
  grip.attach(10);
  grip.write(0);  // gripper open
  angle = angleFor(START_CUP);
  base.write(angle);
  Serial.println("ErrP robot arm: which cup does the person want?");
  Serial.println("(the arm does not know - it only reads the brain's oops signals)");
  delay(1500);

  for (int i = 0; i < N_STEPS; i++) {{
    Serial.print("Move ");
    Serial.print(i + 1);
    if (KIND[i] == 0) Serial.print(": arm turns to cup ");
    else Serial.print(": 90% sure - reaching for cup ");
    Serial.println(CUP[i] + 1);
    turnTo(angleFor(CUP[i]));
    delay(300);
    showBrain(OOPS[i]);
    if (KIND[i] == 1 && OOPS[i]) Serial.println("   final check said oops - not grabbing, keep looking");
  }}

  Serial.print("Grabbing cup ");
  Serial.println(CHOICE + 1);
  turnTo(angleFor(CHOICE));
  for (int a = 0; a <= 90; a++) {{ grip.write(a); delay(10); }}
  Serial.print("The person wanted cup ");
  Serial.print(WANTED + 1);
  Serial.println(CHOICE == WANTED ? " - CORRECT!" : " - wrong cup");
}}

void loop() {{}}
"""


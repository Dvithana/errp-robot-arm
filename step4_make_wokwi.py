def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--person", type=int, default=6, choices=range(1, 7))
    p.add_argument("--seed", type=int, default=1, help="change it to play a different game")
    p.add_argument("--synthetic", action="store_true")
    p.add_argument("--out", default="wokwi")
    a = p.parse_args()
    out = Path(a.out); out.mkdir(exist_ok=True)

    if a.synthetic:
        from step2b_all_subjects import synthetic_people
        data = synthetic_people()
        label = f"fake person {a.person}, game {a.seed}"
    else:
        from errp_data import load_subject
        data = {s: load_subject(s) for s in range(1, 7)}
        label = f"person {a.person}, game {a.seed}"

    print(f"Training the detector on everyone except person {a.person}...", flush=True)
    det, hit, false = train_on_others(data, a.person)
    X, y = data[a.person][0], data[a.person][1]
    said = det.predict(X) == 1

    target, choice, steps = play_recorded(said[y == 1], said[y == 0], hit, false, np.random.default_rng(a.seed))
    print(f"\nGame ({label}): the person wanted cup {target + 1}")
    for i, (kind, cup, oops) in enumerate(steps, 1):
        what = "turn to" if kind == 0 else "reach for"
        print(f"  move {i:2d}: {what} cup {cup + 1} -> brain says {'OOPS' if oops else 'ok'}")
    print(f"Arm grabs cup {choice + 1}: {'CORRECT' if choice == target else 'wrong'}")

    sketch = SKETCH.format(
        label=label, n=len(steps), target=target, choice=choice, start=N_CUPS // 2,
        kind=", ".join(str(k) for k, _, _ in steps),
        cup=", ".join(str(c) for _, c, _ in steps),
        oops=", ".join(str(int(o)) for _, _, o in steps))
    (out / "sketch.ino").write_text(sketch)
    (out / "diagram.json").write_text(json.dumps(DIAGRAM, indent=2))
    print(f"\nSaved {out / 'sketch.ino'} and {out / 'diagram.json'} - paste them into Wokwi.")


if __name__ == "__main__":
    main()
